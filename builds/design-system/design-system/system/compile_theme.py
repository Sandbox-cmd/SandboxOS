#!/usr/bin/env python3
"""compile_theme — design/tokens/*.css is the single source; everything else is emitted.

The emit.py pattern applied to the soul: this compiler parses the LOCKED web tokens
(colors, type scale) and generates (a) interface/tui/bootleg.tcss — the Textual
theme — and (b) interface/tokens.json — the palette any renderer may read. Both
carry a sha256 sidecar line; a hand edit is drift with a one-glance receipt.
Deterministic: same tokens in, same bytes out.

*One palette, compiled everywhere — the hand-kept theme rotted exactly once, elsewhere.*
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
COLORS = ROOT / "tokens" / "colors.css"
OUT_TCSS = ROOT / "pressed" / "bootleg.tcss"
OUT_JSON = ROOT / "pressed" / "tokens.json"

VAR_RX = re.compile(r"--([\w-]+):\s*(#[0-9A-Fa-f]{6})\b")


def load_palette() -> dict:
    if not COLORS.exists():
        raise FileNotFoundError("tokens/colors.css missing — the soul is the source; nothing compiles without it")
    return {name: hexv.upper() for name, hexv in VAR_RX.findall(COLORS.read_text())}


def main() -> int:
    p = load_palette()
    need = ["crt-black", "crt-950", "crt-900", "crt-800", "ash-500", "ash-300",
            "paper", "signal", "amber", "amber-glow", "green", "cyan", "blue",
            "magenta", "hazard", "alert"]
    missing = [n for n in need if n not in p]
    if missing:
        print("compile_theme: REFUSED — tokens missing from the canon: " + ", ".join(missing))
        return 1
    tcss = f"""/* GENERATED by system/compile_theme.py from system/tokens/colors.css.
   Do not hand-edit — re-compile; a differing hash IS the drift signal.
   The six laws in terminal form: mono base, one earned accent per view. */
Screen {{ background: {p['crt-black']}; color: {p['signal']}; }}
* {{ scrollbar-background: {p['crt-950']}; scrollbar-color: {p['crt-800']}; }}
.mono {{ color: {p['signal']}; }}
.dim {{ color: {p['ash-500']}; }}
.paper {{ color: {p['paper']}; }}
.accent-amber {{ color: {p['amber']}; }}
.accent-green {{ color: {p['green']}; }}
.accent-cyan {{ color: {p['cyan']}; }}
.accent-magenta {{ color: {p['magenta']}; }}
.accent-alert {{ color: {p['alert']}; }}
.slap {{ background: {p['hazard']}; color: {p['crt-black']}; text-style: bold; }}
.slap-alert {{ background: {p['alert']}; color: {p['signal']}; text-style: bold; }}
.diecut {{ border: heavy {p['signal']}; }}
.diecut-dim {{ border: heavy {p['crt-800']}; }}
#sidebar {{ background: {p['crt-950']}; border-right: heavy {p['crt-800']}; width: 26; }}
#sidebar .channel {{ padding: 0 1; }}
#sidebar .channel.active {{ background: {p['amber']}; color: {p['crt-black']}; text-style: bold; }}
#body {{ padding: 1 2; }}
#palette {{ dock: bottom; display: none; background: {p['crt-950']};
            border: heavy {p['amber']}; }}
Footer {{ background: {p['crt-950']}; color: {p['ash-300']}; }}
Header {{ background: {p['crt-black']}; color: {p['amber']}; text-style: bold; }}
"""
    OUT_TCSS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TCSS.write_text(tcss, encoding="utf-8")
    tokens = {"_generated": "system/compile_theme.py — system/tokens/colors.css is the source",
              "mood": "workbench",   # the one mood that exists; jailbroken/afterhours are
                                     # reserved words in craft/tongue.md, no knob until designed
              "palette": {k: p[k] for k in sorted(p)},
              "laws": {"one_accent_per_view": True, "green_only_on_verified": True,
                       "supercolor": "cartridges only", "magenta": "the partner's one voiced line",
                       "emoji": "never"}}
    OUT_JSON.write_text(json.dumps(tokens, indent=1) + "\n", encoding="utf-8")
    for f in (OUT_TCSS, OUT_JSON):
        digest = hashlib.sha256(f.read_bytes()).hexdigest()[:16]
        print(f"compiled {f.relative_to(ROOT)} · {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
